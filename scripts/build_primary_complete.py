# --- MÔN HỌC BỔ SUNG CHO TỪNG KHỐI LỚP 1 - 5 ---
def build_subject_item(grade, subj_id, subj_name, icon, lessons_data):
    lessons = []
    for num, chap, title, a, m in lessons_data:
        lessons.append({
            "id": f"{subj_id}-b{num}",
            "number": num,
            "chapter": chap,
            "title": title,
            "questions": make_subject_questions(grade, subj_name, title, chap, a, m)
        })
    return {
        "id": f"{subj_id}-{grade}",
        "name": subj_name,
        "icon": icon,
        "lessons": lessons
    }

